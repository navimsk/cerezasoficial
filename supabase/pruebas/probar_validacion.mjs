// Pruebas de la validación de la Edge Function ingesta (node probar_validacion.mjs)
import { validarEvento, validarLote, sha256Hex, igualSeguro } from '../functions/_compartido/eventos.ts'
let f = 0; const ok = (c, m) => { console.log(`${c ? '  ✔' : '  ✘'} ${m}`); if (!c) f++ }
// JSON tal como lo arma contador_eg118.ino (jsonEvento)
const delFirmware = JSON.parse('{"equipo_id":"linea-1","seq":42,"tipo":"caja","n":1,"dur_ms":100,"avance_mm":50,"cajas":1,"total":10,"vel_mm_s":500,"ts":"2026-11-16T12:00:00.123Z"}')
const hb = JSON.parse('{"equipo_id":"linea-1","seq":43,"tipo":"heartbeat","n":0,"dur_ms":0,"avance_mm":0,"cajas":0,"total":10,"vel_mm_s":500,"extra":{"estado":"normal","haz":false,"rssi":-60,"pendientes":0,"filtrados":0,"uptime_s":30,"perdidos_cola":0}}')
ok(validarEvento(delFirmware) === null, 'acepta un evento caja del firmware v2')
ok(validarEvento(hb) === null, 'acepta un heartbeat sin ts (equipo sin hora)')
ok(validarEvento({ ...delFirmware, tipo: 'ajuste', n: -2 }) === null, 'acepta ajuste negativo')
ok(validarEvento({ ...delFirmware, tipo: 'nada' }) === 'tipo_invalido', 'rechaza tipo desconocido')
ok(validarEvento({ ...delFirmware, seq: 0 }) === 'seq_invalido', 'rechaza seq 0')
ok(validarEvento({ ...delFirmware, seq: 1.5 }) === 'seq_invalido', 'rechaza seq decimal')
ok(validarEvento({ ...delFirmware, n: 5 }) === 'n_incoherente', 'rechaza caja con n=5')
ok(validarEvento({ ...hb, n: 1 }) === 'n_incoherente', 'rechaza heartbeat con n≠0')
ok(validarEvento({ ...delFirmware, ts: 'ayer' }) === 'ts_invalido', 'rechaza ts no ISO')
ok(validarEvento([1]) === 'no_es_objeto', 'rechaza arreglo como evento')
const l = validarLote([delFirmware, { ...delFirmware, seq: -1 }, hb])
ok(l.validos.length === 2 && l.rechazados.length === 1 && l.rechazados[0].indice === 1, 'lote mixto: 2 válidos, 1 rechazado con índice')
ok('error' in validarLote(Array(501).fill(delFirmware)), 'rechaza lotes de más de 500')
ok(validarLote(delFirmware).validos.length === 1, 'acepta un evento suelto (no arreglo)')
ok(await sha256Hex('abc') === 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad', 'sha256 correcto')
ok(igualSeguro('abc', 'abc') && !igualSeguro('abc', 'abd') && !igualSeguro('a', 'ab'), 'comparación segura')
console.log(f ? `${f} fallas` : 'Validación OK'); process.exit(f ? 1 : 0)
